export function isMainLabelCodePoint(codePoint: number): boolean {
  return LABEL_FONT_RANGES.some(([start, end]) => codePoint >= start && codePoint <= end);
}
export function isSupportedLabelCodePoint(codePoint: number): boolean {
  return (
    isMainLabelCodePoint(codePoint) ||
    LABEL_SYMBOL_FONT_RANGES.some(([start, end]) => codePoint >= start && codePoint <= end)
  );
}
