import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import fc from 'fast-check';
import { afterEach, describe, expect, it } from 'vitest';
import { WebSocket } from 'ws';
import { createPairedRoute, type PairedRoute, pairedHmac } from '../../src/server/paired-route';
import { enabledSecret, ORIGIN, PAIRING } from '../helpers/feed-socket';
import { propertyOptions, unicodeStrings } from './fc-options';

const PROTOCOL = 'mux-xr-property-v1';

/** A limiter that never blocks, so a run cannot charge the budget of the next run. */
const permissiveLimiter = {
  blocked: () => false,
  saturated: () => false,
  begin: () => () => undefined,
  fail: () => undefined,
  size: () => 0,
};

let route: PairedRoute | undefined;
let server: Server | undefined;
const authCalls: string[] = [];

const startServer = async (): Promise<string> => {
  const http = createServer((_request, response) => {
    response.writeHead(404).end();
  });
  const built = createPairedRoute({
    protocol: PROTOCOL,
    allowedOrigins: [ORIGIN],
    loadSecret: enabledSecret,
    limiter: permissiveLimiter,
    maxPayloadBytes: 8 * 1024,
    maxConnections: 64,
    reportGates: false,
    reportFailures: 'none',
    emit: () => undefined,
    authTimeoutMs: 1500,
    macMaterial: (message) => String(message.zip ?? ''),
    onAuthenticated: (connection, message) => {
      authCalls.push(String(message.zip));
      connection.sendJson({ type: 'ok' });
      return undefined;
    },
  });
  http.on('upgrade', (request, socket, head) => built.handleUpgrade(request, socket, head));
  await new Promise<void>((resolve) => http.listen(0, '127.0.0.1', resolve));
  route = built;
  server = http;
  const address = http.address() as AddressInfo;
  return `ws://127.0.0.1:${address.port}`;
};

afterEach(async () => {
  route?.close();
  route = undefined;
  const closing = server;
  server = undefined;
  if (closing) await new Promise<void>((resolve) => closing.close(() => resolve()));
  authCalls.length = 0;
});

type Attempt = { code: string | undefined; close: number };

/**
 * One handshake: connect, answer the challenge with `build(nonce)`, await the close. The route
 * answers failures with `{type:'error', code}` and closes 1008; an accepted auth sends
 * `{type:'ok'}` and stays open, so the client closes first with 1000.
 */
const attempt = (url: string, build: (nonce: string) => string | Buffer): Promise<Attempt> =>
  new Promise((resolve, reject) => {
    const socket = new WebSocket(url, { origin: ORIGIN });
    let code: string | undefined;
    const settle = (close: number): void => {
      clearTimeout(deadline);
      resolve({ code, close });
    };
    const deadline = setTimeout(() => {
      socket.removeAllListeners();
      socket.terminate();
      reject(new Error('handshake did not close within the per-run deadline'));
    }, 1000);
    socket.on('message', (data) => {
      const frame = JSON.parse(String(data)) as { type?: string; nonce?: string; code?: string };
      if (frame.type === 'challenge' && typeof frame.nonce === 'string') {
        socket.send(build(frame.nonce));
        return;
      }
      if (frame.type === 'error') {
        code = frame.code;
        return;
      }
      // The auth was accepted: close from this side so the run ends promptly.
      socket.close(1000);
    });
    socket.on('error', (error) => {
      clearTimeout(deadline);
      reject(error);
    });
    socket.on('close', settle);
  });

/** A MAC that differs from the correct one in exactly the generated byte. */
const wrongMacAuth = (zip: string, flip: number, nonce: string): string => {
  const mac = pairedHmac(Buffer.from(PAIRING), PROTOCOL, nonce, zip);
  mac[flip % mac.length] ^= 255;
  return JSON.stringify({ type: 'auth', zip, mac: mac.toString('base64') });
};

describe('paired-route handshake properties', () => {
  it('never authenticates an arbitrary first frame and closes with 1008', {
    timeout: 30_000,
  }, async () => {
    const url = await startServer();
    const firstFrames = fc.oneof(
      unicodeStrings({ maxLength: 128 }).map((text) => ({ kind: 'text' as const, text })),
      fc.jsonValue().map((value) => ({ kind: 'json' as const, text: JSON.stringify(value) })),
      fc.uint8Array({ maxLength: 64 }).map((bytes) => ({ kind: 'binary' as const, bytes })),
      fc
        .record({
          zip: fc.stringMatching(/^[a-z0-9 .-]{0,16}$/),
          flip: fc.nat(31),
        })
        .map(({ zip, flip }) => ({ kind: 'wrong-mac' as const, zip, flip })),
    );
    await fc.assert(
      fc.asyncProperty(firstFrames, async (frame) => {
        const before = authCalls.length;
        const outcome = await attempt(url, (nonce) => {
          if (frame.kind === 'text') return frame.text;
          if (frame.kind === 'json') return frame.text;
          if (frame.kind === 'binary') return Buffer.from(frame.bytes);
          return wrongMacAuth(frame.zip, frame.flip, nonce);
        });
        expect(authCalls.length).toBe(before);
        expect(outcome.code).toBeDefined();
        expect(outcome.close).toBe(1008);
      }),
      propertyOptions(),
    );
  });

  it('authenticates exactly once on a well-formed auth with the correct MAC', {
    timeout: 30_000,
  }, async () => {
    const url = await startServer();
    await fc.assert(
      fc.asyncProperty(fc.stringMatching(/^[a-z0-9 .-]{0,16}$/), async (zip) => {
        const before = authCalls.length;
        const outcome = await attempt(url, (nonce) => {
          const mac = pairedHmac(Buffer.from(PAIRING), PROTOCOL, nonce, zip);
          return JSON.stringify({ type: 'auth', zip, mac: mac.toString('base64') });
        });
        expect(authCalls.length).toBe(before + 1);
        expect(authCalls).toContain(zip);
        expect(outcome.code).toBeUndefined();
        expect(outcome.close).toBe(1000);
      }),
      propertyOptions(),
    );
  });
});
